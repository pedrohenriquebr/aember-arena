const dictionaries: Record<Language, Dict> = { en, ptBR };

export function readLanguage(): Language {
  try {
    const saved = localStorage.getItem("aember-arena-language");
    if (saved === "en" || saved === "ptBR") return saved;
    if (typeof navigator !== "undefined" && navigator.language.toLowerCase().startsWith("pt")) return "ptBR";
  } catch {
    // Default below.
  }
  return "en";
}

export function saveLanguage(language: Language): void {
  try {
    localStorage.setItem("aember-arena-language", language);
  } catch {
    // Language stays active for this session even without storage.
  }
}

export function createTranslator(language: Language) {
  const dict = dictionaries[language];
  return (key: string, vars?: Record<string, string | number>): string => {
    let value = dict[key] ?? dictionaries.en[key] ?? key;
    if (vars) {
      for (const [name, replacement] of Object.entries(vars)) {
        value = value.replace(new RegExp(`\\{${name}\\}`, "g"), String(replacement));
      }
    }
    return value;
  };
}

export type Translator = ReturnType<typeof createTranslator>;
